# Упражнения раздела 4.2.1: строки.
#
#   ruby exercises/4_2_1_strings.rb

# 1. Переменные city и state (подставьте свои значения).
city = "Kazan"
state = "RT"

# 2. Вывод через интерполяцию: город и штат через запятую и пробел.
puts "#{city}, #{state}"

# 3. То же, но разделитель - символ табуляции.
puts "#{city}\t#{state}"

# 4. Результат при замене двойных кавычек на одинарные: интерполяция и \t
#    не работают, строка выводится буквально.
puts '#{city}\t#{state}'
