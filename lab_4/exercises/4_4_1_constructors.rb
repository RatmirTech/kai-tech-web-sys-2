# Упражнения раздела 4.4.1: конструкторы.
#
#   ruby exercises/4_4_1_constructors.rb

# 1. Литеральный конструктор диапазона целых чисел от 1 до 10.
literal = 1..10
p literal

# 2. Именованный конструктор через класс Range: new принимает два аргумента.
named = Range.new(1, 10)
p named

# 3. Литеральный и именованный конструкторы дают равные объекты.
puts literal == named
